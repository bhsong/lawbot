"""Export response types without invoking the API, data collection or a model server."""

import argparse
import json
from pathlib import Path

from law_calendar.models import CalendarMonth, CalendarStatus, ChangePage, ErpNews, ErpUpdates, HoldPage, PublicDetail

TARGET = Path(__file__).resolve().parents[2] / 'frontend/src/law-calendar/api-types.ts'


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(item) for item in schema['anyOf'])
    if schema.get('type') == 'array':
        return f'({ts_type(schema["items"])})[]'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}[
        schema['type']
    ]


def generate():
    schemas = {}
    for model in (CalendarMonth, CalendarStatus, ChangePage, ErpNews, ErpUpdates, HoldPage, PublicDetail):
        root = model.model_json_schema()
        schemas.update(root.pop('$defs', {}))
        schemas[model.__name__] = root
    blocks = ['// Generated by python -m law_calendar.schema. Do not edit by hand.']
    for name, schema in sorted(schemas.items()):
        fields = [
            f'  {key}{"?" if key not in schema.get("required", []) else ""}: {ts_type(value)}'
            for key, value in schema['properties'].items()
        ]
        blocks.append('export interface ' + name + ' {\n' + '\n'.join(fields) + '\n}')
    return '\n\n'.join(blocks) + '\n'


def main():
    parser = argparse.ArgumentParser(description='Generate public calendar TypeScript types')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            parser.exit(1, 'Calendar TypeScript contract is stale\n')
    else:
        TARGET.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
